'use strict';

const Fs = require('node:fs');
const Path = require('node:path');
const { ReadDocument, StoreCatalog2K22 } = require('../../Server/Source/Storage/StoreCatalog2K22');
const { Crc32 } = require('../../Server/Source/Core/Crc32');

const Output = process.argv[2];
if (!Output) throw new Error('usage: node GenerateCpuWardrobe.js <output header> [catalog]');
const Source = process.argv[3] || Path.resolve(__dirname, '../../Server/Storage/Inventory/StoreCatalog2K22.json');
const Document = ReadDocument(Source);
const Catalog = new StoreCatalog2K22(Document);
// Store cells add tags beyond the group tag; keep precisely the purchasable catalog views.
const Purchasable = new Set(['Clothing', 'Accessories', 'Shoes'].flatMap(Group =>
    Catalog.groupItems[Group].filter(Item => Item.tag_crcs.length > 1).map(Item => Item.item_id)));
const Hashes = new Set(), ShoeHashes = new Set();
function Variants(Name) {
    const Match = /^([^{}]*)\{([^{}]+)\}([^{}]*)$/.exec(Name);
    if (!Match) {
        if (/[{}]/.test(Name)) throw new Error(`unsupported clothing alternatives: ${Name}`);
        return [Name];
    }
    return Match[2].split(',').map(Choice => Match[1] + Choice + Match[3]);
}
for (const Item of Document.items) {
    if (!Purchasable.has(Number(Item.item))) continue;
    for (const Name of Item.content) {
        if (Item.itemType === 5) {
            const Match = /\/(shoe_[^/.]+)\.[0-9a-f-]{36}\.iff$/i.exec(Name);
            if (!Match) throw new Error(`unsupported shoe resource: ${Name}`);
            ShoeHashes.add(Crc32(Match[1].toLowerCase()));
        } else for (const Variant of Variants(Name)) Hashes.add(Crc32(Variant.toLowerCase()));
    }
}
function ArrayText(Name, Values) {
    const Sorted = [...Values].sort((A, B) => A - B), Lines = [];
    if (!Sorted.length) throw new Error(`purchasable CPU ${Name} catalog is empty`);
    for (let I = 0; I < Sorted.length; I += 8)
        Lines.push('    ' + Sorted.slice(I, I + 8).map(Hash => `0x${Hash.toString(16).padStart(8, '0')}U`).join(', ') + ',');
    return `inline constexpr uint32_t ${Name}[] = {\n${Lines.join('\n')}\n};\n`;
}
const Header = '// Generated by Tools/GenerateCpuWardrobe.js from the purchasable store catalog.\n' +
    '#pragma once\nnamespace CpuWardrobeCatalog\n{\n' + ArrayText('Clothing', Hashes) + ArrayText('Shoes', ShoeHashes) + '}\n';
Fs.mkdirSync(Path.dirname(Path.resolve(Output)), { recursive: true });
if (!Fs.existsSync(Output) || Fs.readFileSync(Output, 'utf8') !== Header) Fs.writeFileSync(Output, Header);
console.log(`CPU wardrobe: ${Purchasable.size} purchasable items, ${Hashes.size} clothing CRCs, ${ShoeHashes.size} shoe CRCs`);
